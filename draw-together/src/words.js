// ── Word picking ─────────────────────────────────────────────

// The longest a clue may be. The word-choice card (public/index.html
// #ov-choose, styled by .big-word in styles.css) is a fixed-width card sized
// for a normal word or short phrase, and a clue should be readable at a
// glance, so pickWord() never offers anything longer than this. No regular
// word comes close; most Chaos-mode scenario prompts do, so Chaos draws only
// from its shorter prompts. The bank itself is kept within the cap too
// (every entry over 30 characters was removed), and pickWord() still checks,
// so a longer entry added later is never offered.
export const MAX_CLUE_LEN = 30;

export function pickWord(settings, used, rand = Math.random) {
  const cats = settings.categories || ['everything'];
  const all = cats.includes('everything');
  // 'Everything' means everything except Maisie's category, which is opt-in:
  // a word that is only tagged maisie needs the chip picked on purpose.
  const inCats = (x) => all ? x.c.some((c) => c !== 'maisie') : x.c.some((c) => cats.includes(c));
  const diffOk = (x) =>
    settings.difficulty === 'easy' ? x.d === 'easy'
    : settings.difficulty === 'silly' ? x.d === 'silly'
    : settings.difficulty === 'hard' ? x.d === 'hard'
    : settings.difficulty === 'chaos' ? x.d === 'chaos'
    // 'mixed' (the default) never surfaces hard-mode or chaos-mode words by
    // accident - both tiers are opt-in only.
    : x.d !== 'hard' && x.d !== 'chaos';
  const lenOk = (x) => x.w.length <= MAX_CLUE_LEN;
  const usedSet = new Set(used);
  const tries = [
    (x, i) => !usedSet.has(i) && inCats(x) && diffOk(x) && lenOk(x),
    (x, i) => !usedSet.has(i) && inCats(x) && lenOk(x),
    (x, i) => !usedSet.has(i) && diffOk(x) && lenOk(x),
    (x, i) => !usedSet.has(i) && lenOk(x),
  ];
  for (const ok of tries) {
    const pool = [];
    WORDS.forEach((x, i) => { if (ok(x, i)) pool.push(i); });
    if (pool.length) return { index: pool[Math.floor(rand() * pool.length)], reset: false };
  }
  // Every eligible word has already been used this game: start over, but
  // still never past the length cap (an all-different-tomorrow reset
  // shouldn't be the one way a too-long prompt sneaks through).
  const freshPool = [];
  WORDS.forEach((x, i) => { if (lenOk(x)) freshPool.push(i); });
  const pool = freshPool.length ? freshPool : WORDS.map((_, i) => i);
  return { index: pool[Math.floor(rand() * pool.length)], reset: true };
}

// ── Length hint for guessers ─────────────────────────────────

// The letter count of each word in the answer, for guessers who can't
// see the word itself. A row of one-box-per-letter blanks reads fine
// on a normal screen, but wraps and re-breaks confusingly when the
// page is pinch-zoomed, so instead each word becomes a single numeral
// that can't be misread no matter how the line wraps.
// "Ice cream cone" -> [3, 5, 4]   "T-Rex" -> [5]
export function wordShape(w) {
  return w.split(' ').filter(Boolean).map((tok) => tok.length);
}

// ── Guess matching ───────────────────────────────────────────

const STOP = new Set(['a', 'an', 'the', 'in', 'on', 'with', 'wearing', 'eating', 'holding',
  'having', 'playing', 'reading', 'brushing', 'its', 'at', 'of', 'and', 'is', 'my', 'some',
  // Chaos-mode scenario prompts ("A firefighter arguing with a dinosaur over a
  // traffic cone") are built from a small set of recurring template verbs and
  // fillers - stripping them too leaves just the nouns actually worth guessing.
  'arguing', 'discovering', 'inside', 'stealing', 'hiding', 'from', 'over', 'trying', 'teaching',
  'how', 'to', 'getting', 'interview', 'job', 'accidentally', 'becoming', 'stuck', 'extremely',
  'dramatically', 'overdressed', 'covered', 'terrified', 'furious', 'suspicious', 'confident',
  'avoiding', 'riding', 'escaping', 'searching', 'wrestling', 'juggling', 'repairing', 'building',
  'driving', 'cooking', 'selling', 'conducting', 'piloting', 'photographing', 'destroying', 'fighting',
  'chasing', 'carrying', 'rescuing', 'misunderstanding', 'underwater', 'terrible', 'ever', 'worst',
  'tiny', 'giant', 'enormous']);

export function normalize(s) {
  return String(s || '')
    .toLowerCase()
    .normalize('NFKD').replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/g, ' ')
    .trim();
}
const squash = (s) => normalize(s).replace(/ /g, '');
const singular = (t) => (t.length > 3 && t.endsWith('s') && !t.endsWith('ss') ? t.slice(0, -1) : t);

function lev(a, b, max) {
  if (Math.abs(a.length - b.length) > max) return max + 1;
  let prev = Array.from({ length: b.length + 1 }, (_, i) => i);
  for (let i = 1; i <= a.length; i++) {
    const cur = [i];
    let rowMin = i;
    for (let j = 1; j <= b.length; j++) {
      cur[j] = Math.min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1));
      rowMin = Math.min(rowMin, cur[j]);
    }
    if (rowMin > max) return max + 1;
    prev = cur;
  }
  return prev[b.length];
}
// How many typos we forgive (little fingers, big words)
const allowance = (len) => (len >= 9 ? 2 : len >= 5 ? 1 : 0);

function tokenMatch(key, tok) {
  const a = singular(key), b = singular(tok);
  if (a === b) return true;
  return lev(a, b, allowance(a.length)) <= allowance(a.length);
}

// Returns 'correct' | 'close' | 'wrong'
export function checkGuess(guess, entry) {
  const g = squash(guess);
  if (!g) return 'wrong';
  const answers = [entry.w, ...entry.also];
  let close = false;
  for (const ans of answers) {
    const a = squash(ans);
    if (g === a || singular(g) === singular(a)) return 'correct';
    const d = lev(g, a, 3);
    if (d <= allowance(a.length)) return 'correct';
    if (a.length >= 4 && d <= allowance(a.length) + 1) close = true;
  }
  // Multi-word prompts: every key word present (any order) counts.
  const keys = normalize(entry.w).split(' ').filter((t) => t && !STOP.has(t));
  if (keys.length > 1) {
    const toks = normalize(guess).split(' ').filter((t) => t && !STOP.has(t));
    const hits = keys.filter((k) => toks.some((t) => tokenMatch(k, t))).length;
    if (hits === keys.length) return 'correct';
    if (hits > 0) close = true;
  }
  return close ? 'close' : 'wrong';
}
